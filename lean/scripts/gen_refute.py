#!/usr/bin/env python3
"""Generate lean/BoltProof/Bridge/Glue/SimpleMulti/Refute.lean: the type pairs the parity check refuses."""
import os as _os
LEAN = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
WORK = _os.environ.get('GLUE_WORK', _os.path.join(LEAN, '.lake', 'glue-work'))
_os.makedirs(WORK, exist_ok=True)
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chunks as C
ARMS = [(1961, 2426), (2591, 2609), (3186, 3623), (3773, 3790), (1426, 2715), (2715, 3897), (3899, 4652)]
UNFOLD = C.unfold(423, 5000, keep=ARMS)
TYPES = [0x20, 0x21, 0x22, 0x23, 0x24, 0x25]
def refused(ty, nty):
    if ty % 2 == nty % 2: return True            # same parity
    if ty % 2 == 1 and nty + 1 != ty: return True  # a settle into another mode's type
    return False
out = ["""import BoltProof.Bridge.Glue.SimpleMulti.Enforced

/-!
# The refused type pairs

The parity check (suffix 528, `Gadgets/Parity.lean`) admits a commit only from a settle-typed token and a settle
only into the spent commit type's own settle type (`nextTxoType + 1 = txoType`). Each theorem here runs the suffix
symbolically on a refused pair until the driver stops and refutes the check's `OP_EQUALVERIFY` fact, a closed
equation `decide` evaluates to false (`refuteLit`). A run that carries such a fact cannot succeed: the symbolic
driver records an `OP_EQUALVERIFY` as a fact without checking it, so these theorems are also what keeps the
path theorems from being vacuous. Generated by the glue's `gen_refute.py`; regenerate rather than edit.
-/

set_option autoImplicit false
set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
set_option maxHeartbeats 100000000
set_option maxRecDepth 100000

namespace BoltProof.Glue.SimpleMulti

open BsvScript BsvScript.Params BsvScript.Numbers BsvScript.Machine BsvScript.Gadget
open BoltProof.Bridge.Generated

open Lean Meta Elab Tactic in
/-- Closes the goal from a hypothesis whose type is a closed proposition that `decide` refutes. -/
elab "refuteLit" : tactic => withMainContext do
  let g ← getMainGoal
  let tgt ← g.getType
  for d in (← getLCtx) do
    if d.isImplementationDetail then continue
    let t ← instantiateMVars d.type
    if t.hasFVar || t.hasMVar then continue
    unless ← isProp t do continue
    let mv ← mkFreshExprMVar (mkNot t)
    let ok ← try
        let gs ← Lean.Elab.Term.TermElabM.run' (Lean.Elab.Tactic.run mv.mvarId! (evalTactic (← `(tactic| decide))))
        pure gs.isEmpty
      catch _ => pure false
    if ok then
      g.assign (← mkAppOptM ``absurd #[t, tgt, d.toExpr, ← instantiateMVars mv])
      replaceMainGoal []
      return
  throwError "refuteLit: no closed hypothesis is refuted by decide"
"""]
for ty in TYPES:
    for nty in TYPES:
        if not refused(ty, nty): continue
        why = 'the same parity' if ty % 2 == nty % 2 else "a settle into another mode's type"
        out.append(f"""/-- `txoType = 0x{ty:x}`, `nextTxoType = 0x{nty:x}`: {why}, refused. -/
theorem refuse_{ty:x}_{nty:x} {{env : Env}} (he : EnvOK env) {{k t : Bytes}} {{r : GOut}} {{f : Fields}} {{a : Args}}
    {{S A : List Bytes}} {{C : Cond}} {{cs : Bytes}} {{m kk : Nat}} (hact : C.isActive = true)
    (hpre : castToBool a.pre = true) (hvar : List.take 1 (List.drop 104 a.pre) = [0xfd])
    (hty : f.ty = [0x{ty:x}]) (hnty : a.nty = [0x{nty:x}])
    (h : run Eval.opExec env (SimpleMulti.suffix ++ k) t (St (f.stack ++ (a.stack ++ S)) A m C kk cs) = r)
    (hr : r.IsOk) : False := by
  obtain ⟨-, m', k', h⟩ := prologue he hact hpre h hr
  rw [suffix_drop_38_append, pushTxBlock_eq] at h
  replace h := pushTx_shape he (by simp [hact]) h hr
  obtain ⟨_, _, h⟩ := h
  simp only [stack38, guardFlag, hasGpFlag, {UNFOLD}, List.cons_append, List.nil_append] at h
  sym_all h hvar hty hnty
  refuteLit
""")
out.append('end BoltProof.Glue.SimpleMulti\n')
open(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Refute.lean', 'w').write('\n'.join(out))
print('refute generated', sum(1 for a in TYPES for b in TYPES if refused(a, b)))
