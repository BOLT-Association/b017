#!/usr/bin/env python3
"""Generate the fungible path theorems (lean/BoltProof/Bridge/Glue/SimpleMulti/Paths/*.lean) and the umbrella."""
import os as _os
LEAN = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
WORK = _os.environ.get('GLUE_WORK', _os.path.join(LEAN, '.lake', 'glue-work'))
_os.makedirs(WORK, exist_ok=True)
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chunks as C
ARMS = [(1961, 2426), (2591, 2609), (3186, 3623), (3773, 3790), (1426, 2715), (2715, 3897), (3899, 4652)]
UNFOLD = C.unfold(423, 5000, keep=ARMS)
GP = '--gp' in sys.argv   # whether the commit paths need the genesis and grandparent hypotheses
HEADER = """import BoltProof.Bridge.Glue.SimpleMulti.Enforced

/-!
# {title}

{doc}

Generated by the glue's `gen_sm.py`; regenerate rather than edit.
-/

set_option autoImplicit false
set_option linter.unusedSimpArgs false
set_option maxHeartbeats 100000000
set_option maxRecDepth 100000

namespace BoltProof.Glue.SimpleMulti

open BsvScript BsvScript.Params BsvScript.Numbers BsvScript.Machine BsvScript.Gadget
open BoltProof.Bridge.Generated
open BoltProof.Glue.MinSimple (reached_of_append)

"""
def commit(ty, nty):
    name = f'commit_{ty:x}_{nty:x}'
    gp = ' (hpar : ¬ decode f.parent = 0) (hgp : ¬ decode f.gp = 0)' if GP else ''
    gpargs = ' hpar hgp' if GP else ''
    split = 'fun _ => (by factF)' if nty == 0x23 else 'fun h23 => absurd (hnty.symm.trans h23) (by decide)'
    merge = 'fun _ => (by factF)' if nty == 0x25 else 'fun h25 => absurd (hnty.symm.trans h25) (by decide)'
    mode = {0x21: 'transfer', 0x23: 'split', 0x25: 'merge'}[nty]
    spent = {0x20: 'settled transfer', 0x22: 'settled split', 0x24: 'settled merge'}[ty]
    return f"""/-- A {mode} commit (`nextTxoType = 0x{nty:x}`) spending a {spent} token (`txoType = 0x{ty:x}`), either value of the input-index argument. -/
theorem {name} {{env : Env}} (he : EnvOK env) {{k t : Bytes}} {{r : GOut}} {{f : Fields}} {{a : Args}}
    {{S A : List Bytes}} {{C : Cond}} {{cs : Bytes}} {{m kk : Nat}} (hact : C.isActive = true)
    (hpre : castToBool a.pre = true) (hvar : List.take 1 (List.drop 104 a.pre) = [0xfd])
    (hty : f.ty = [0x{ty:x}]) (hnty : a.nty = [0x{nty:x}]){gp}
    (h : run Eval.opExec env (SimpleMulti.suffix ++ k) t (St (f.stack ++ (a.stack ++ S)) A m C kk cs) = r)
    (hr : r.IsOk) : Enforced env f a cs ∧ Ends env a k t r C cs := by
  obtain ⟨hguard, m', k', h⟩ := prologue he hact hpre h hr
  rw [suffix_drop_38_append, pushTxBlock_eq] at h
  have hpt : PushTxReached env a.pre cs := by
    obtain ⟨r', hst, hok⟩ := reached_of_append pushTxBlock_framed h hr
    exact ⟨_, _, _, _, _, _, r', by simp [hact], hst, hok⟩
  replace h := pushTx_shape he (by simp [hact]) h hr
  obtain ⟨_, _, h⟩ := h
  simp only [stack38, guardFlag, hasGpFlag, {UNFOLD}, List.cons_append, List.nil_append] at h
  by_cases hidx : decode a.inIdx = 0
  all_goals
    sym_all h hvar hty hnty{gpargs} hidx
    enforced_normF h
    refine ⟨⟨hpt, (by factF), (by factF), (by factF), (by factF), (by factF), (by factF), (by factF),
      {split}, {merge},
      ?outs, (by factF), ?prev, fun hG => hguard hG, (by factF), (by factF), (by factF), (by factF)⟩, _, _, _, _, h⟩
    case prev =>
      simp (config := {{ decide := true }}) only [prevoutsOf, hnty, hidx, eq_self_iff_true, ↓reduceIte, List.append_assoc]
      factF
    case outs =>
      simp (config := {{ decide := true }}) only [expectedOuts, hnty, hidx, eq_self_iff_true, ↓reduceIte, commitLock,
        mergeLock1, inIdxByte, lockOf, tokenOut, proofOut, zeros, scBalPush, scPkhPush, scParentPush, scIssuerPush,
        scSuffix, List.append_assoc, List.cons_append, List.nil_append, List.singleton_append, List.length_cons]
      factF
"""
files = {}
for nty, mode in [(0x21, 'Transfer'), (0x23, 'Split'), (0x25, 'Merge')]:
    body = HEADER.format(title=f'The {mode.lower()} commits',
        doc=f'The three commit spends into a {mode.lower()} commit (`nextTxoType = 0x{nty:x}`), from each settled type, for either value of the input-index argument: each run establishes `Enforced` and ends with the owner check on top.')
    for ty in (0x20, 0x22, 0x24): body += commit(ty, nty) + '\n'
    body += 'end BoltProof.Glue.SimpleMulti\n'
    files[f'Commit{mode}'] = body
os.makedirs(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Paths', exist_ok=True)
for n, b in files.items():
    open(f'{LEAN}/BoltProof/Bridge/Glue/SimpleMulti/Paths/{n}.lean', 'w').write(b)
umbrella = '\n'.join(f'import BoltProof.Bridge.Glue.SimpleMulti.Paths.{n}' for n in files) + """

/-!
# The fungible paths

The path theorems of the `SimpleMultiBOLT` suffix, one file per next type.
-/
"""
open(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Paths.lean', 'w').write(umbrella)
print('generated', list(files))
