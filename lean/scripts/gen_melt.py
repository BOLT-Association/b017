import chunks as C
ARMS = [(1961, 2426), (2591, 2609), (3186, 3623), (3773, 3790), (1426, 2715), (2715, 3897), (3899, 4652)]
UNFOLD = C.unfold(0, 5000, keep=ARMS)
out = f"""import BoltProof.Bridge.Glue.SimpleMulti.Enforced

/-!
# The melt

Without a preimage (`castToBool preimage = false`) the suffix skips the spend arm (`OP_IFDUP OP_IF`,
suffix 36–4679) and runs the melt branch (4680–4695): the sighash byte, the owner's key hash and the
encodings, then the owner's `OP_CHECKSIG`. The prologue's issuer guard (suffix 0–29) applies as on every
path. Nothing constrains the outputs: a melt spends the token out of the covenant (`Accepts`' melt clause is a
scope assumption, see the plan's decision for Finding 1). The run does not read the spent type, so the theorem
takes no type hypothesis. Generated by the glue's `gen_melt.py`; regenerate rather than edit.
-/

set_option autoImplicit false
set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
set_option maxHeartbeats 100000000
set_option maxRecDepth 100000

namespace BoltProof.Glue.SimpleMulti

open BsvScript BsvScript.Params BsvScript.Numbers BsvScript.Machine BsvScript.Gadget
open BoltProof.Bridge.Generated

/-- What the suffix enforces on a melt: the issuer guard, the owner's key hash, the signature's sighash byte and
the two encodings. -/
structure EnforcedMelt (env : Env) (f : Fields) (a : Args) : Prop where
  issuer : GuardF f → f.issuer = a.pk ∧ a.nty ≠ [0x25] ∧ a.nty ≠ [0x27]
  owner : Hash.hash160 a.pk = f.pkh
  sigType : List.drop (List.length a.sig - 1) a.sig = [0x41]
  sigEnc : Ops.Crypto.checkSignatureEncoding env a.sig = .ok ()
  pkEnc : Ops.Crypto.checkPubKeyEncoding env a.pk = .ok ()

/-- **A melt.** Without a preimage, a successful run of the suffix enforces `EnforcedMelt` and ends with the
owner's signature check on top, for any spent type, parent and grandparent. -/
theorem melt {{env : Env}} (he : EnvOK env) {{k t : Bytes}} {{r : GOut}} {{f : Fields}} {{a : Args}}
    {{S A : List Bytes}} {{C : Cond}} {{cs : Bytes}} {{m kk : Nat}} (hact : C.isActive = true)
    (hpre : castToBool a.pre = false)
    (h : run Eval.opExec env (SimpleMulti.suffix ++ k) t (St (f.stack ++ (a.stack ++ S)) A m C kk cs) = r)
    (hr : r.IsOk) : EnforcedMelt env f a ∧ Ends env a k t r C cs := by
  simp only [SimpleMulti.suffix, Fields.stack, Args.stack, {UNFOLD}, List.cons_append, List.nil_append,
    List.append_assoc] at h
  by_cases hpar : decode f.parent = 0 <;> by_cases hgp : decode f.gp = 0
  all_goals
    sym_all h hpre hpar hgp
    enforced_normF h
    simp (config := {{ failIfUnchanged := false }}) only [decode_ite_one_nil_eq_zero] at *
  · exact ⟨⟨fun _ => ⟨(by factF), (by factF), (by factF)⟩, (by factF), (by factF), (by factF), (by factF)⟩, _, _, _, _, h⟩
  · exact ⟨⟨fun _ => ⟨(by factF), (by factF), (by factF)⟩, (by factF), (by factF), (by factF), (by factF)⟩, _, _, _, _, h⟩
  · exact ⟨⟨fun _ => ⟨(by factF), (by factF), (by factF)⟩, (by factF), (by factF), (by factF), (by factF)⟩, _, _, _, _, h⟩
  · exact ⟨⟨fun hG => hG.elim (fun h0 => absurd h0 hpar) (fun h0 => absurd h0 hgp), (by factF), (by factF),
      (by factF), (by factF)⟩, _, _, _, _, h⟩

end BoltProof.Glue.SimpleMulti
"""
open(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Melt.lean', 'w').write(out)
