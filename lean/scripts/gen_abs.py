#!/usr/bin/env python3
"""Generate lean/BoltProof/Bridge/Glue/SimpleMulti/Lock.lean: the fungible lock, its pushes and its decoder."""
import os as _os
LEAN = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
WORK = _os.environ.get('GLUE_WORK', _os.path.join(LEAN, '.lake', 'glue-work'))
_os.makedirs(WORK, exist_ok=True)
FIELDS = [('bal', 16), ('balCommit', 16), ('pkh', 20), ('com', 20), ('com2', 20), ('ogp', 36), ('ty', 1),
          ('outIdx', 1), ('parent', 36), ('gp', 36), ('issuer', 33)]
offs = []; o = 0
for n, w in FIELDS: offs.append(o); o += 1 + w
TOTAL = o   # 246
def tail(k):
    """The lock from the push of field k on, as a right-nested term."""
    s = 'SimpleMulti.suffix'
    for n, w in reversed(FIELDS[k:]):
        s = f'{w} :: (f.{n} ++ {s})'
    return s
def dtail(k):
    """The lock from the data of field k on."""
    n, w = FIELDS[k]
    rest = tail(k + 1) if k + 1 < len(FIELDS) else 'SimpleMulti.suffix'
    return f'f.{n} ++ {rest}'
L = []
L.append(f"""import BoltProof.Bridge.Glue.SimpleMulti.Spec

/-!
# The `SimpleMultiBOLT` lock

The locking script is the eleven field pushes followed by the suffix (`lockScript`); `WF` is the widths the pushes
carry ({' + '.join(str(w) for _, w in FIELDS)} bytes of data, {TOTAL} bytes with the push opcodes), `decodeLock`
reads the fields back (`decodeLock_lockScript`), and `lock_pushes` runs the pushes symbolically, so a run of the
whole lock is a run of the suffix from `Fields.stack`. Generated by the glue's `gen_abs.py`; regenerate rather
than edit.
-/

set_option autoImplicit false

namespace BoltProof.Glue.SimpleMulti

open BsvScript BsvScript.Params BsvScript.Numbers BsvScript.Machine BsvScript.Gadget
open BoltProof.Bridge.Generated

/-- Well-formed lock fields: the widths the eleven pushes carry. -/
structure WF (f : Fields) : Prop where""")
for n, w in FIELDS: L.append(f'  {n} : f.{n}.length = {w}')
L.append(f"""
/-- The locking script: the eleven pushes, `bal` first and `issuer` last, then the suffix. -/
def lockScript (f : Fields) : Bytes :=
  {tail(0)}

theorem lockScript_length {{f : Fields}} (hwf : WF f) : (lockScript f).length = {TOTAL} + SimpleMulti.suffix.length := by
  simp [lockScript, {', '.join('hwf.' + n for n, _ in FIELDS)}]; omega

/-- The eleven pushes put the fields on the stack, `issuer` on top: a run of the lock is a run of the suffix
from `Fields.stack`. -/
theorem lock_pushes {{env : Env}} (he : EnvOK env) {{t : Bytes}} {{r : GOut}} {{f : Fields}} {{S A : List Bytes}}
    {{C : Cond}} {{cs : Bytes}} {{m kk : Nat}} (hact : C.isActive = true) (hwf : WF f)
    (h : run Eval.opExec env (lockScript f) t (St S A m C kk cs) = r) (hr : r.IsOk) :
    ∃ m' k', run Eval.opExec env SimpleMulti.suffix t (St (f.stack ++ S) A m' C k' cs) = r := by
  unfold lockScript at h""")
for n, w in FIELDS:
    L.append(f"""  obtain ⟨-, _, _, h⟩ := inv_push_{w} he hact h hr
  rw [List.take_left' hwf.{n}, List.drop_left' hwf.{n}] at h""")
L.append("""  exact ⟨_, _, h⟩
""")
# decoder
conds = ' ∧ '.join([f's.length = {TOTAL} + SimpleMulti.suffix.length'] + [f's[{offs[k]}]? = some {w}' for k, (n, w) in enumerate(FIELDS)] + [f's.drop {TOTAL} = SimpleMulti.suffix'])
fields = ', '.join(f'{n} := (s.drop {offs[k] + 1}).take {w}' for k, (n, w) in enumerate(FIELDS))
L.append(f"""/-- The fields read back off a locking script: the push opcodes at their places, the suffix after them,
nothing else. -/
def decodeLock (s : Bytes) : Option Fields :=
  if {conds} then
    some {{ {fields} }}
  else none

/-! The lock's layout: what sits at each push and after it, for the decoder and for the welds. -/
""")
# drop lemmas: push k at offs[k] (k>0) and data at offs[k]+1
prev = None
for k, (n, w) in enumerate(FIELDS):
    po = offs[k]; do = po + 1
    if k == 0:
        L.append(f"theorem lockScript_drop_{do} (f : Fields) : (lockScript f).drop {do} =\n    {dtail(k)} := rfl")
    else:
        pn, pw = FIELDS[k - 1]
        pdo = offs[k - 1] + 1
        L.append(f"""theorem lockScript_drop_{po} {{f : Fields}} (hwf : WF f) : (lockScript f).drop {po} =
    {tail(k)} := by
  rw [show ({po} : Nat) = {pdo} + {pw} from rfl, ← List.drop_drop, lockScript_drop_{pdo}{'' if k == 1 else ' hwf'}, List.drop_left' hwf.{pn}]""")
        L.append(f"""theorem lockScript_drop_{do} {{f : Fields}} (hwf : WF f) : (lockScript f).drop {do} =
    {dtail(k)} := by
  rw [show ({do} : Nat) = {po} + 1 from rfl, ← List.drop_drop, lockScript_drop_{po} hwf]; rfl""")
ln, lw = FIELDS[-1]
L.append(f"""theorem lockScript_drop_{TOTAL} {{f : Fields}} (hwf : WF f) : (lockScript f).drop {TOTAL} = SimpleMulti.suffix := by
  rw [show ({TOTAL} : Nat) = {offs[-1] + 1} + {lw} from rfl, ← List.drop_drop, lockScript_drop_{offs[-1] + 1} hwf, List.drop_left' hwf.{ln}]
""")
gets = ', '.join([f'g _ _ _ (lockScript_drop_{offs[k]} hwf)' for k in range(1, len(FIELDS))])
datas = ', '.join(['lockScript_drop_1'] + [f'lockScript_drop_{offs[k] + 1} hwf' for k in range(1, len(FIELDS))])
takes = ', '.join(f'List.take_left\' hwf.{n}' for n, _ in FIELDS)
L.append(f"""/-- A well-formed lock decodes to its fields. -/
theorem decodeLock_lockScript {{f : Fields}} (hwf : WF f) : decodeLock (lockScript f) = some f := by
  have g : ∀ (n : Nat) (b : Nat) (r : Bytes), (lockScript f).drop n = b :: r → (lockScript f)[n]? = some b := by
    intro n b r hn
    have := @List.getElem?_drop _ (lockScript f) n 0
    rw [Nat.add_zero] at this
    rw [← this, hn]; rfl
  unfold decodeLock
  rw [ite_eq_left ⟨lockScript_length hwf, rfl, {gets}, lockScript_drop_{TOTAL} hwf⟩]
  congr 1
  rw [{datas}, {takes}]

end BoltProof.Glue.SimpleMulti
""")
open(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Lock.lean', 'w').write('\n'.join(L))
print('lock generated, total', TOTAL)
