import os as _os
LEAN = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
WORK = _os.environ.get('GLUE_WORK', _os.path.join(LEAN, '.lake', 'glue-work'))
_os.makedirs(WORK, exist_ok=True)
# gen_rebuiltB.py: names the second rebuild's bytes (both cases) from the region facts and gpOutB.
R=LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Regions.lean'
SETTLE=LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/Settle.lean'
r=open(R).read(); st=open(SETTLE).read()
def body(src,name):
    i=src.index('abbrev '+name+' ')
    return src[i:].split('\n')[0], src[i:].split('\n')[1].strip()
def matchparen(t,j):
    d=0
    for k in range(j,len(t)):
        if t[k]=='(':d+=1
        elif t[k]==')':
            d-=1
            if d==0: return k
    raise Exception
out=['''import BoltProof.Bridge.Glue.SimpleMulti.Settle

/-!
# The second rebuild's bytes

A merge settle's second rebuild (suffix 2715–3896) rebuilds the other lineage's grandparent in one of two cases
on the spent lock's output index, hashes it against the other grandparent's txid (`rebuildB_k_fact1`) and names the
co-spent outpoint as that hash and the fourth interop slot (`gpOutB_k`). This file names the hashed bytes
(`rebuiltB1`, `rebuiltB2`) so both facts read as equations on them. Generated by the glue's `gen_rebuiltB.py`;
regenerate rather than edit.
-/

set_option autoImplicit false
set_option maxHeartbeats 4000000
set_option maxRecDepth 100000
set_option linter.unusedVariables false

namespace BoltProof.Glue.SimpleMulti

open BsvScript BsvScript.Numbers
''']
for k in (1,2):
    hdr,f1=body(r,'rebuildB_%d_fact1'%k)
    params=hdr[hdr.index('rebuildB_%d_fact1'%k)+len('rebuildB_%d_fact1'%k):hdr.rindex(': Prop :=')].strip()
    assert f1.startswith('Hash.hash256 (')
    j=f1.index('('); e=matchparen(f1,j); X=f1[j+1:e]
    assert f1[e+1:].strip()=='= List.take 32 ((item T 41))', f1[e+1:]
    ghdr,g=body(st,'gpOutB_%d'%k)
    gparams=ghdr[ghdr.index('gpOutB_%d'%k)+len('gpOutB_%d'%k):ghdr.rindex(': Bytes :=')].strip()
    assert gparams==params, (gparams, params)
    import re
    names=' '.join(re.findall(r'\(([^:]*):', params)).split()
    A=' '.join(names)
    out.append('''/-- The bytes the second rebuild hashes, case %d. -/
def rebuiltB%d %s : Bytes :=
  %s

theorem rebuildB_%d_fact1_eq %s :
    rebuildB_%d_fact1 %s = (Hash.hash256 (rebuiltB%d %s) = List.take 32 (item T 41)) := rfl

theorem gpOutB_%d_eq %s :
    gpOutB_%d %s = Hash.hash256 (rebuiltB%d %s) ++ item T 60 := rfl
'''%(k,k,params,X,k,params,k,A,k,A,k,params,k,A,k,A))
out.append('end BoltProof.Glue.SimpleMulti\n')
open(LEAN + '/BoltProof/Bridge/Glue/SimpleMulti/RebuiltB.lean','w').write('\n'.join(out))
print('ok')
