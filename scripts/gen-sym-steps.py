OBT = "  obtain ⟨hgen, hera, hmin, hminif, hfork, hcs⟩ := he\n"

def lemma(name, doc, op, pre, post, extra_binders="", facts=None, pre_alt="A", post_alt="A",
          post_cond="C", needs_act=True, setup="  rw [run.eq_2] at h\n", closer=None):
    binders = "{env : Env} {g t : Bytes} {r : GOut} " + extra_binders + "{S A : List Bytes} {C : Cond} {cs : Bytes} {m k : Nat}"
    act = " (hact : C.isActive = true)" if needs_act else ""
    concl = f"∃ m' k', run Eval.opExec env g t (St ({post}) {post_alt} m' {post_cond} k' cs) = r"
    if facts:
        concl = " ∧ ".join(facts) + " ∧\n      " + concl
    if closer is None:
        closer = "  all_goals inv_close h hr\n"
    return f'''/-- {doc} -/
theorem {name} {binders} (he : EnvOK env){act}
    (h : run Eval.opExec env ({op} :: g) t (St ({pre}) {pre_alt} m C k cs) = r) (hr : r.IsOk) :
    {concl} := by
{OBT}{setup}  inv_simp at h
  inv_split h
{closer}'''

def fact_closer(facts_tac):
    return (f"  all_goals first\n    | (subst h; simp at hr)\n    | (refine ⟨{facts_tac}, _, _, h⟩)\n"
            f"    | (simp only [ne_eq, *]; refine ⟨{facts_tac}, _, _, h⟩)\n")

L = []
