 ("inv_not", "`OP_NOT`: the top replaced by `1` if it is zero, else `0`.", "Op.OP_NOT", "{x : Bytes} ", "x :: S", "encode (if decode x = 0 then 1 else 0) :: S"),
 ("inv_0notequal", "`OP_0NOTEQUAL`: the top replaced by `1` if it is non-zero, else `0`.", "Op.OP_0NOTEQUAL", "{x : Bytes} ", "x :: S", "encode (if decode x = 0 then 0 else 1) :: S"),
 ("inv_1add", "`OP_1ADD`: the top incremented.", "Op.OP_1ADD", "{x : Bytes} ", "x :: S", "encode (decode x + 1) :: S"),
 ("inv_1sub", "`OP_1SUB`: the top decremented.", "Op.OP_1SUB", "{x : Bytes} ", "x :: S", "encode (decode x - 1) :: S"),
 ("inv_add", "`OP_ADD` on `b1` (below) and `b2` (top): the sum pushed.", "Op.OP_ADD", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (decode b1 + decode b2) :: S"),
 ("inv_sub", "`OP_SUB`: the difference `b1 - b2` pushed.", "Op.OP_SUB", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (decode b1 - decode b2) :: S"),
 ("inv_booland", "`OP_BOOLAND`: `1` if both are non-zero, else `0`.", "Op.OP_BOOLAND", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (if ¬ decode b1 = 0 ∧ ¬ decode b2 = 0 then 1 else 0) :: S"),
 ("inv_boolor", "`OP_BOOLOR`: `1` if either is non-zero, else `0`.", "Op.OP_BOOLOR", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (if ¬ decode b1 = 0 ∨ ¬ decode b2 = 0 then 1 else 0) :: S"),
 ("inv_lessthan", "`OP_LESSTHAN`: `1` if `b1 < b2`, else `0`.", "Op.OP_LESSTHAN", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (if decode b1 < decode b2 then 1 else 0) :: S"),
 ("inv_lte", "`OP_LESSTHANOREQUAL`: `1` if `b1 ≤ b2`, else `0`.", "Op.OP_LESSTHANOREQUAL", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (if decode b1 ≤ decode b2 then 1 else 0) :: S"),
 ("inv_gte", "`OP_GREATERTHANOREQUAL`: `1` if `b1 ≥ b2`, else `0`.", "Op.OP_GREATERTHANOREQUAL", "{b2 b1 : Bytes} ", "b2 :: b1 :: S", "encode (if decode b1 ≥ decode b2 then 1 else 0) :: S"),
 ("inv_hash256", "`OP_HASH256`: the top replaced by its double SHA-256.", "Op.OP_HASH256", "{x : Bytes} ", "x :: S", "Hash.hash256 x :: S"),
 ("inv_hash160", "`OP_HASH160`: the top replaced by its RIPEMD-160 of SHA-256.", "Op.OP_HASH160", "{x : Bytes} ", "x :: S", "Hash.hash160 x :: S"),
 ("inv_sha256", "`OP_SHA256`: the top replaced by its SHA-256.", "Op.OP_SHA256", "{x : Bytes} ", "x :: S", "Hash.sha256 x :: S"),
